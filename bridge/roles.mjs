export const ROLE_KEYS = Object.keys(ROLES);

export function getRole(key) {
  return ROLES[key] || ROLES.friend;
}

export function rolePersona(key, maxChars) {
  const role = getRole(key);
  return role.persona.replace(/\{maxChars\}/g, String(maxChars || role.maxChars || 40));
}
